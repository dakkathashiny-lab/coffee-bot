def filter_products(entities):
    df = products.copy()
    if "product_name" in entities and not entities.get("is_lookup"):
        return df[df["Product_Name"] == entities["product_name"]]
    if "brand" in entities and not entities.get("is_lookup"):
        df = df[df["Brand"].str.lower() == entities["brand"].lower()]
    if "region" in entities:
        df = df[df["Region"].str.lower() == entities["region"].lower()]
    elif "state" in entities:
        df = df[df["State"].str.lower() == entities["state"].lower()]
    if "strength" in entities and not entities.get("is_lookup"):
        df = df[df["Strength"].str.lower() == entities["strength"].lower()]
    if "milk" in entities and not entities.get("is_lookup"):
        if entities["milk"] == "Black":
            # almost any coffee can be had black - only exclude products that
            # inherently already contain milk powder/creamer (premixes)
            df = df[~df["Milk_Compatibility"].str.contains("Milk Powder|Creamer Included", case=False, regex=True)]
        else:
            df = df[df["Milk_Compatibility"].str.contains(entities["milk"], case=False)]
    if "flavor" in entities and not entities.get("is_lookup"):
        df = df[df["Flavor_Profile"].str.contains(entities["flavor"], case=False)]
    if "type" in entities and not entities.get("is_lookup"):
        df = df[df["Type"].str.lower() == entities["type"].lower()]
    if "brew_format" in entities and not entities.get("is_lookup"):
        df = df[df["Brew_Format"].str.lower() == entities["brew_format"].lower()]
    if "packaging" in entities and not entities.get("is_lookup"):
        df = df[df["Packaging_Type"].str.lower() == entities["packaging"].lower()]
    if "budget" in entities and not entities.get("is_lookup"):
        df = df[df["Price_INR"] <= entities["budget"]]
    if "budget_min" in entities and not entities.get("is_lookup"):
        df = df[df["Price_INR"] >= entities["budget_min"]]
    return df


