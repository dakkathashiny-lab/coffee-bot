def format_price(row):
    if pd.notna(row.get("Price_Per_100g")) and str(row.get("Price_Per_100g")).strip():
        return f"₹{row['Price_INR']} for {row['Pack_Size']} (≈₹{int(float(row['Price_Per_100g']))}/100g)"

    pack = str(row.get("Pack_Size", ""))
    pack_l = pack.lower()
    if "ml" in pack_l:
        return f"₹{row['Price_INR']} for {pack} (sold by volume, not weight)"
    if "pod" in pack_l or "capsule" in pack_l:
        return f"₹{row['Price_INR']} for {pack} (sold as a fixed pack of pods, not by weight)"
    if "sachet" in pack_l or "bag" in pack_l:
        return f"₹{row['Price_INR']} for {pack} (sold as a fixed pack, not by loose weight)"
    return f"₹{row['Price_INR']} for {pack}"


def relaxed_matches(entities):
    """Retry using only the location (region/state), dropping other
    constraints, so we can suggest the closest thing we actually have."""
    if "region" in entities:
        loose = products[products["Region"].str.lower() == entities["region"].lower()]
        if not loose.empty:
            return loose, "region", entities["region"]
    if "state" in entities:
        loose = products[products["State"].str.lower() == entities["state"].lower()]
        if not loose.empty:
            return loose, "state", entities["state"]
    return pd.DataFrame(), None, None


def format_no_match(entities):
    loose, level, label = relaxed_matches(entities)
    if not loose.empty:
        budget_note = ""
        if "budget" in entities:
            cheapest = loose["Price_INR"].min()
            if cheapest > entities["budget"]:
                budget_note = (f" (the cheapest option from {label} is ₹{int(cheapest)}, "
                               f"above your ₹{entities['budget']} budget)")
        lines = [f"I don't have anything matching *all* of that{budget_note}, but here's what I do have from {label}:\n"]
        for _, row in loose.head(3).iterrows():
            lines.append(f"- **{row['Brand']} — {row['Product_Name']}** "
                         f"({row['Brew_Format']}, {row['Strength']}) — {format_price(row)}")
        return "\n".join(lines)

    # nothing matched at all - point to what IS covered rather than a dead end
    if "budget" in entities:
        cheapest_overall = products["Price_INR"].min()
        return (f"I couldn't find anything under ₹{entities['budget']} — my cheapest product overall is "
                f"₹{int(cheapest_overall)}. Try raising your budget, or drop it to see all options.")
    sample_regions = ", ".join(sorted(products["Region"].unique())[:6])
    return (
        "I couldn't find a match for that. My catalog currently covers coffee from "
        f"regions like {sample_regions}, and more. Try naming one of those, or a "
        "preference like strong/mild, or a milk type."
    )


def format_results(df, entities):
    if df.empty:
        return format_no_match(entities)

    lines = []
    state_for_flair = None
    if "region" in entities:
        info = regions[regions["Region"].str.lower() == entities["region"].lower()]
        if not info.empty:
            row = info.iloc[0]
            state_for_flair = row["State"]
            lines.append(f"**{row['Region']}, {row['State']}** typically produces "
                          f"{row['Coffee_Type']} coffee with **{row['Flavor_Notes']}** notes.\n")
    elif "state" in entities:
        state_for_flair = entities["state"]

    if state_for_flair and state_for_flair in STATE_FLAIR:
        lines.insert(0, STATE_FLAIR[state_for_flair] + "\n")

    reason = build_reason(entities)
    if reason and not entities.get("is_lookup"):
        lines.append(reason)

    if entities.get("is_lookup"):
        # explicit "what's available in X" browsing request - a list is the right format here
        lines.append(f"Here are {len(df)} matching option(s):\n")
        for _, row in df.head(5).iterrows():
            lines.append(
                f"- **{row['Brand']} — {row['Product_Name']}** "
                f"({row['Brew_Format']}, {row['Strength']}, {row['Milk_Compatibility']} milk friendly, "
                f"flavor: {row['Flavor_Profile']}) — {format_price(row)}"
            )
    else:
        # default: one confident pick, matching every stated preference - not a list to browse
        pick = df.iloc[0]
        lines.append(
            f"**My pick: {pick['Brand']} — {pick['Product_Name']}**\n"
            f"{pick['Brew_Format']}, {pick['Strength']}, {pick['Milk_Compatibility']} milk friendly, "
            f"flavor: {pick['Flavor_Profile']} — {format_price(pick)}"
        )
        remaining = len(df) - 1
        if remaining > 0:
            lines.append(f"\n_This matches everything you asked for. {remaining} other option(s) "
                         f"also fit just as well if you'd like to see them - just ask._")

    if "requested_grams" in entities:
        requested = entities["requested_grams"]
        pack_grams = []
        for _, row in df.head(5).iterrows():
            m = re.search(r"(\d+)\s*g\b", str(row["Pack_Size"]))
            if m:
                pack_grams.append(int(m.group(1)))
        if pack_grams and requested not in pack_grams:
            sizes = ", ".join(f"{g}g" for g in sorted(set(pack_grams)))
            lines.append(f"\nNote: these aren't sold in {requested}g packs specifically — "
                         f"the pack size(s) available here are {sizes}.")

    return "\n".join(lines)


def build_reason(entities):
    """Short human-readable explanation of what drove the filtering."""
    parts = []
    if "product_name" in entities:
        return f"Matched the specific product: {entities['product_name']}.\n"
    if "brand" in entities:
        parts.append(f"brand: {entities['brand']}")
    if "region" in entities:
        parts.append(f"grown in {entities['region']}")
    elif "state" in entities:
        parts.append(f"from {entities['state']}")
    if "strength" in entities:
        parts.append(f"{entities['strength'].lower()} strength")
    if "milk" in entities:
        if entities["milk"] == "Black":
            parts.append("works well black, no milk needed")
        else:
            parts.append(f"works with {entities['milk'].lower()} milk")
    if "flavor" in entities:
        parts.append(f"{entities['flavor']} flavor notes")
    if "brew_format" in entities:
        parts.append(f"prepared as {entities['brew_format'].lower()}")
    if "packaging" in entities:
        parts.append(f"in {entities['packaging'].lower()}")
    if "budget_min" in entities and "budget" in entities:
        parts.append(f"priced between ₹{entities['budget_min']} and ₹{entities['budget']}")
    elif "budget_min" in entities:
        parts.append(f"above ₹{entities['budget_min']}")
    elif "budget" in entities:
        parts.append(f"within ₹{entities['budget']}")

    if not parts:
        return ""
    return "Matched because you wanted: " + ", ".join(parts) + ".\n"


def log_interaction(user_input, entities, scope, num_matches):
    """Append this turn to a local CSV log - useful evidence for your
    capstone report (most-asked regions, common clarifying questions, etc).
    Note: on free hosting like Streamlit Community Cloud this file resets
    whenever the app restarts/sleeps, so download it periodically if you
    want to keep the history, or point LOG_FILE at a mounted/shared path."""
    is_new = not os.path.exists(LOG_FILE)
    try:
        with open(LOG_FILE, "a", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            if is_new:
                writer.writerow(["timestamp", "user_input", "scope", "entities", "num_matches"])
            writer.writerow([datetime.now().isoformat(timespec="seconds"),
                              user_input, scope, str(entities), num_matches])
    except OSError:
        pass  # don't let logging failures break the chat experience


def log_rating(recommended_product, stars):
    """Append a star rating for a specific recommendation - this is the
    direct 'did this help you' signal for your capstone evaluation, separate
    from the end-of-session Google Form."""
    is_new = not os.path.exists(RATING_LOG_FILE)
    try:
        with open(RATING_LOG_FILE, "a", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            if is_new:
                writer.writerow(["timestamp", "recommended_product", "stars"])
            writer.writerow([datetime.now().isoformat(timespec="seconds"),
                              recommended_product, stars])
    except OSError:
        pass


