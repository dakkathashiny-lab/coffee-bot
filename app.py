def match_product_name(text, cutoff=0.5, min_precision=0.5):
    """Word-overlap matcher for specific product/estate names (e.g. 'Krishnagiri
    Estate'). Unlike the region/brand matcher, this uses set overlap rather than
    character windows, since product names are often longer than what someone
    actually types (e.g. 'krishnagiri dark roast' vs 'Krishnagiri Estate (Dark Roast)').
    Requires both recall (how much of the product name is covered) and precision
    (how much of the query is explained by the product) to be high, so a broad
    browsing query like 'strong filter coffee from Chikmagalur' doesn't get
    wrongly narrowed to one specific product just because those words happen to
    also appear in that product's name."""
    text_words = set(re.findall(r"[a-z0-9]+", text.lower().replace(".", "")))
    if not text_words:
        return None, 0.0
    best, best_score = None, 0.0
    for name in PRODUCT_VOCAB:
        name_words = set(re.findall(r"[a-z0-9]+", name.lower().replace(".", ""))) - PRODUCT_NAME_STOPWORDS
        if not name_words:
            continue
        overlap = text_words & name_words
        if not overlap:
            continue
        recall = len(overlap) / len(name_words)
        precision = len(overlap) / len(text_words)
        if precision < min_precision or len(overlap) < 2:
            continue
        if recall > best_score:
            best_score, best = recall, name
    return (best, best_score) if best_score >= cutoff else (None, 0.0)


# ---------- FUZZY ENTITY EXTRACTION ----------
def _best_fuzzy_match(text, vocab, cutoff=0.7, exclude_words=None):
    """Find the vocab entry that best fuzzy-matches something in `text`.
    Tries word windows of length 1-3, plus a no-space concatenation,
    so misheard/typo'd multi-word names (e.g. 'Chikmong Lurong') still
    match single-word region names (e.g. 'Chikmagalur').
    exclude_words: window text (e.g. 'coffee') that should never be treated
    as a match candidate, even if it scores high by coincidence - needed
    because generic words like 'coffee' or 'bean' can score deceptively
    high against brand names like 'Coffeeza' or 'Beanstalk'."""
    text_l = text.lower()
    words = text_l.split()
    exclude = set(exclude_words or [])
    best, best_score = None, 0.0

    for candidate in vocab:
        cand_l = candidate.lower()
        cand_words = cand_l.split()
        n = len(cand_words)
        for i in range(len(words) - n + 1):
            window = " ".join(words[i:i + n])
            if window in exclude:
                continue
            score = difflib.SequenceMatcher(None, window, cand_l).ratio()
            if score > best_score:
                best_score, best = score, candidate
        # also try a 2-word window concatenated with no space, in case
        # a one-word name got typed/misheard as two words
        for i in range(len(words) - 1):
            if words[i] in exclude or words[i + 1] in exclude:
                continue
            concat = words[i] + words[i + 1]
            score = difflib.SequenceMatcher(None, concat, cand_l.replace(" ", "")).ratio()
            if score > best_score:
                best_score, best = score, candidate

    return (best, best_score) if best_score >= cutoff else (None, 0.0)


def extract_entities(text):
    text_l = text.lower()
    entities = {}

    foreign_match = next((b for b in FOREIGN_BRAND_KEYWORDS if b in text_l), None)
    if foreign_match:
        entities["foreign_brand"] = foreign_match

    region, score = _best_fuzzy_match(text, REGION_VOCAB)
    if region:
        entities["region"] = region
    else:
        state, score = _best_fuzzy_match(text, STATE_VOCAB)
        if state:
            entities["state"] = state

    brand, score = _best_fuzzy_match(text, BRAND_VOCAB, cutoff=0.9, exclude_words=GENERIC_COFFEE_KEYWORDS)
    if not brand and BRAND_MATCH_ALIASES:
        alias, score = _best_fuzzy_match(text, list(BRAND_MATCH_ALIASES.keys()),
                                           cutoff=0.9, exclude_words=GENERIC_COFFEE_KEYWORDS)
        if alias:
            brand = BRAND_MATCH_ALIASES[alias]
    if brand:
        entities["brand"] = brand

    product_name, score = match_product_name(text)
    if product_name:
        entities["product_name"] = product_name

    for level, keywords in STRENGTH_KEYWORDS.items():
        if any(k in text_l for k in keywords):
            entities["strength"] = level.capitalize()
            break

    if any(p in text_l for p in MILK_LOOKUP_PHRASES):
        entities["milk_lookup"] = True
    else:
        for milk_type, keywords in MILK_KEYWORDS.items():
            if any(k in text_l for k in keywords):
                entities["milk"] = milk_type
                break

    for flavor in FLAVOR_KEYWORDS:
        if flavor in text_l:
            entities["flavor"] = flavor
            break
    if "flavor" not in entities and "milk" not in text_l and any(w in text_l for w in FLAVOR_TRIGGER_WORDS):
        entities["unknown_flavor"] = True

    for t in TYPE_KEYWORDS:
        if t in text_l:
            entities["type"] = t.title()
            break

    if any(p in text_l for p in PACKAGING_LOOKUP_PHRASES):
        entities["packaging_lookup"] = True
    else:
        for pack_type, keywords in PACKAGING_KEYWORDS.items():
            if any(k in text_l for k in keywords):
                entities["packaging"] = pack_type
                break

    if any(p in text_l for p in BREW_FORMAT_LOOKUP_PHRASES):
        entities["brew_format_lookup"] = True
    else:
        for fmt, keywords in BREW_FORMAT_KEYWORDS.items():
            if any(k in text_l for k in keywords):
                entities["brew_format"] = fmt
                break

    budget_match = re.search(r"(?:under|below|less than|within)\s*(?:rs\.?|₹)?\s*(\d+)", text_l)
    range_match = re.search(r"(?:between|priced)?\s*(?:rs\.?|₹)?\s*(\d+)\s*(?:to|-|and)\s*(?:rs\.?|₹)?\s*(\d+)", text_l)
    above_match = re.search(r"above\s*(?:rs\.?|₹)?\s*(\d+)", text_l)
    bare_price_match = re.search(r"(?:₹\s*(\d+)|(\d+)\s*(?:rs\.?|rupees?))\b", text_l)
    if range_match:
        entities["budget_min"] = int(range_match.group(1))
        entities["budget"] = int(range_match.group(2))
    elif above_match:
        entities["budget_min"] = int(above_match.group(1))
    elif budget_match:
        entities["budget"] = int(budget_match.group(1))
    elif bare_price_match:
        # informal phrasing like "2rs product" or "₹2 coffee" with no under/below/above -
        # treat the mentioned number as the price ceiling, the most sensible interpretation
        entities["budget"] = int(bare_price_match.group(1) or bare_price_match.group(2))
    elif any(k in text_l for k in BUDGET_VAGUE_KEYWORDS):
        entities["budget"] = 250  # rough "budget option" cutoff, tune as you collect real prices

    pack_size_match = re.search(r"(\d+)\s*(?:gram|grams|gm|g)\b", text_l)
    if pack_size_match:
        entities["requested_grams"] = int(pack_size_match.group(1))

    entities["is_lookup"] = any(w in text_l for w in
                                 ["what brand", "which brand", "available in", "brands in", "options in"])
    return entities


def message_scope(text, entities):
    """Returns 'greeting', 'coffee', or 'off_topic'."""
    text_l = text.lower().strip()

    if any(g in text_l for g in GREETING_KEYWORDS) and len(text_l.split()) <= 4:
        return "greeting"

    # any recognized coffee entity (region/state/strength/milk/flavor/type/brew_format)
    # is enough to count the message as coffee-related
    if any(k in entities for k in ("product_name", "brand", "foreign_brand", "region", "state", "strength", "milk", "flavor",
                                    "type", "brew_format", "packaging", "milk_lookup",
                                    "brew_format_lookup", "packaging_lookup", "budget")):
        return "coffee"

    if any(k in text_l for k in GENERIC_COFFEE_KEYWORDS):
        return "coffee"

    return "off_topic"


