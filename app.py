def process_message(text):
    """Single shared pipeline for chat input, quick-start buttons, and the
    sidebar filter, so every path gets logged and answered consistently."""
    # show only the latest exchange, not a growing history - clear everything
    # before adding this new query, so old answers don't stay stacked on screen
    st.session_state["messages"] = []
    st.session_state["messages"].append(("user", text, None))

    # follow-up to "N other options also fit - want to see them?"
    text_l = text.lower().strip()
    last_matches = st.session_state.get("last_matches")
    if (any(p in text_l for p in FOLLOWUP_MORE_PHRASES) or text_l in ("yes", "sure", "ok", "okay"))            and last_matches is not None and len(last_matches) > 1:
        remaining = last_matches.iloc[1:6]
        lines = ["Here are the other options that match just as well:\n"]
        for _, row in remaining.iterrows():
            lines.append(f"- **{row['Brand']} — {row['Product_Name']}** "
                         f"({row['Brew_Format']}, {row['Strength']}) — {format_price(row)}")
        reply = "\n".join(lines)
        log_interaction(text, {}, "coffee", len(remaining))
        st.session_state["messages"].append(("assistant", reply, remaining))
        st.session_state["last_matches"] = None  # shown already, don't offer again
        return

    entities = extract_entities(text)
    scope = message_scope(text, entities)
    products_for_images = None

    if entities.get("foreign_brand"):
        named = entities["foreign_brand"].title()
        alt_entities = {k: v for k, v in entities.items()
                         if k in ("region", "state", "strength", "milk", "flavor", "type", "brew_format")}
        alt_matches = filter_products(alt_entities) if alt_entities else pd.DataFrame()
        if alt_matches.empty:
            alt_matches = products.sample(min(3, len(products)), random_state=42)
        alt_lines = [f"- **{row['Brand']} — {row['Product_Name']}** ({row['Brew_Format']}, {row['Strength']}) — {format_price(row)}"
                     for _, row in alt_matches.head(3).iterrows()]
        reply = (f"I'm a bot built only for Indian-grown coffee, so I don't have data on {named} — "
                 f"that's not an Indian-sourced brand. Here's the closest match from Indian coffee I do have:\n\n"
                 + "\n".join(alt_lines))
        num_matches = len(alt_matches)
        if not alt_matches.empty:
            products_for_images = alt_matches.head(3)
        log_interaction(text, entities, "coffee", num_matches)
        st.session_state["messages"].append(("assistant", reply, products_for_images))
        return

    if scope == "off_topic":
        reply = OFF_TOPIC_MESSAGE
        num_matches = 0
    elif scope == "greeting":
        reply = random.choice(GREETING_REPLIES)
        num_matches = 0
    elif entities.get("milk_lookup"):
        options = ", ".join(available_milk_types())
        reply = f"Here's what I can filter by for milk: **{options}**. Just tell me which one you'd like."
        num_matches = 0
    elif entities.get("brew_format_lookup"):
        options = ", ".join(available_brew_formats())
        reply = (f"I can search by these brew formats: **{options}**. "
                 "For example: Traditional Filter (metal filter/decoction), "
                 "Drip Bag (dip it in your cup), Instant Sachet (just add hot water), "
                 "or Cold Brew Concentrate. Which one suits you?")
        num_matches = 0
    elif entities.get("packaging_lookup"):
        options = ", ".join(sorted(products["Packaging_Type"].unique()))
